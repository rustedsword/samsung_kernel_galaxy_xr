set -euo pipefail

source_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
base=$source_dir/arch/arm64/boot/dts/vendor/qcom/anorakp.dts
board_dir=$source_dir/arch/arm64/boot/dts/samsung/xrvst2
dtc=${DTC:-$source_dir/out/galaxyxr/scripts/dtc/dtc}
revisions=(22 25)

if [[ ${1:-} == --help ]]; then
    cat <<'EOF'
Usage: scripts/merge-galaxyxr-dts.sh

Writes arch/arm64/boot/dts/samsung/xrvst2/anorakp-samsung-xrvst2-revNN.dts
for the board revisions 22 and 25: anorakp.dts with the board overlay
applied, "samsung,xrvst2-revNN" as the first compatible, and what the
Android bootloader adds to the tree at boot (the uH reserved regions,
the DDR type, the splash region of the UEFI frame buffers).

Environment: DTC, the kernel's dtc (default: out/galaxyxr/scripts/dtc/dtc).
Needs fdtoverlay, fdtget and fdtput on the host.
EOF
    exit 0
fi

missing=()
for tool in "$dtc" fdtoverlay fdtget fdtput; do
    command -v "$tool" >/dev/null || missing+=("$tool")
done
if (( ${#missing[@]} )); then
    printf 'Missing tools: %s\n' "${missing[*]}" >&2
    exit 1
fi

work=$(mktemp -d)
trap 'rm -rf -- "$work"' EXIT
"$dtc" -q -I dts -O dtb -o "$work/base.dtb" "$base"
for revision in "${revisions[@]}"; do
    overlay=anorak-sec-xrvst2-usa-open-overlay-r$revision
    tree=$work/merged.dtb
    output=$board_dir/anorakp-samsung-xrvst2-rev$revision.dts

    "$dtc" -q -I dts -O dtb -o "$work/overlay.dtbo" "$board_dir/$overlay.dts"
    fdtoverlay -i "$work/base.dtb" -o "$tree" "$work/overlay.dtbo"

    # fdtoverlay leaves the overlay's root properties out, libufdt takes them
    read -r -a compatible < <(fdtget -t s "$work/overlay.dtbo" / compatible)
    read -r -a board_id < <(fdtget -t x "$work/overlay.dtbo" / qcom,board-id)
    fdtput -t s "$tree" / model "$(fdtget -t s "$work/overlay.dtbo" / model)"
    fdtput -t s "$tree" / compatible "samsung,xrvst2-rev$revision" "${compatible[@]}"
    fdtput -t x "$tree" / qcom,board-id "${board_id[@]}"

    fdtput -c "$tree" /reserved-memory/uh_heap_region /reserved-memory/uh_guest_region
    fdtput -t x "$tree" /reserved-memory/uh_heap_region reg 0 b0200000 0 40000
    fdtput -t x "$tree" /reserved-memory/uh_guest_region reg 0 b1000000 0 1e00000
    fdtput -t x "$tree" /reserved-memory/splash_region reg 0 bfc00000 0 7e90000
    fdtput -t x "$tree" /memory ddr_device_type 8

    {
        printf '/* Generated by scripts/merge-galaxyxr-dts.sh from anorakp.dts and %s.dts */\n' "$overlay"
        "$dtc" -q -I dtb -O dts "$tree"
    } > "$output"
    printf '%s\n' "${output#"$source_dir/"}"
done
